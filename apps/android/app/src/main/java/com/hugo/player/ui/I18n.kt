/**
 * Idioma do app (Configurações → Idioma): pt (padrão), en, es.
 * A tradução é feita na hora de desenhar o texto (o [Text] deste pacote), então a lógica que compara
 * textos continua em português e nada quebra; o que não está no dicionário aparece em português.
 */
object I18n {
    val LANGS = listOf("pt" to "Português (BR)", "en" to "English", "es" to "Español")
    var lang by mutableStateOf("pt")
        private set

    fun init() { lang = AppSettings.language }
    fun set(code: String) { AppSettings.language = code; lang = AppSettings.language }

    fun t(pt: String): String {
        val l = lang
        if (l == "pt" || pt.isEmpty()) return pt
        val i = if (l == "en") 0 else 1
        DICT[pt]?.let { return it[i] }
        // pedaços comuns com número/nome no meio
        for ((rx, out) in PATTERNS) { val m = rx.matchEntire(pt) ?: continue; return out[i](m.groupValues) }
        return pt
    }

    private val PATTERNS: List<Pair<Regex, Array<(List<String>) -> String>>> = listOf(
        Regex("Temporada (\\d+)") to arrayOf({ g -> "Season ${g[1]}" }, { g -> "Temporada ${g[1]}" }),
        Regex("Pronto! (\\d[\\d.]*) itens") to arrayOf({ g -> "Done! ${g[1]} items" }, { g -> "¡Listo! ${g[1]} elementos" }),
        Regex("Baixando\\.\\.\\. (.*)") to arrayOf({ g -> "Downloading... ${g[1]}" }, { g -> "Descargando... ${g[1]}" }),
        Regex("Organizando\\.\\.\\. (.*)") to arrayOf({ g -> "Organizing... ${g[1]}" }, { g -> "Organizando... ${g[1]}" }),
        Regex("(\\d[\\d.]*) canais") to arrayOf({ g -> "${g[1]} channels" }, { g -> "${g[1]} canales" }),
        Regex("(\\d[\\d.]*) filmes") to arrayOf({ g -> "${g[1]} movies" }, { g -> "${g[1]} películas" }),
